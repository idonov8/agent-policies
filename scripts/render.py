#!/usr/bin/env python3
"""Render agent entry points from global.md without changing managed blocks."""
from pathlib import Path
import argparse
ROOT = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser()
p.add_argument('--check', action='store_true')
a = p.parse_args()
core = (ROOT / 'global.md').read_text().rstrip() + '\n'
outputs = {}
for name in ('codex', 'gemini'):
    managed = (ROOT / f'integrations/pushary/{name}.md').read_text()
    target = ROOT / f'agents/{name}.md'
    if target.exists():
        text = target.read_text()
        start = text.find('<!-- BEGIN PUSHARY')
        end = text.find('<!-- END PUSHARY -->')
        if start >= 0 and end >= 0:
            installed = text[start:end + len('<!-- END PUSHARY -->')] + '\n'
            if installed != managed:
                raise SystemExit(f'{target}: managed Pushary block changed; preserve the installed block in integrations/pushary/{name}.md before rendering.')
    outputs[target] = '<!-- Generated by scripts/render.py; edit global.md. -->\n\n' + core + '\n' + managed
outputs[ROOT / 'agents/cursor.mdc'] = '---\ndescription: Shared personal agent policies\nalwaysApply: true\n---\n\n' + core
stale = []
for target, content in outputs.items():
    if not target.exists() or target.read_text() != content:
        stale.append(str(target.relative_to(ROOT)))
        if not a.check:
            target.write_text(content)
if a.check and stale:
    raise SystemExit('Stale generated files: ' + ', '.join(stale))
print('Agent entry points are current.' if a.check else 'Rendered agent entry points.')
